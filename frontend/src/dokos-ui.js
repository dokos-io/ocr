// Curated dokos-ui registration.
//
// We import from the package barrel ("dokos-ui"). The barrel is intentionally
// light: the two heavy components (BDatePicker → @vuepic/vue-datepicker,
// BTextEditor → tiptap) are excluded from it and exposed as opt-in subpaths
// ("dokos-ui/datepicker", "dokos-ui/editor"). Import those directly only where
// needed to keep this app's bundle small.
